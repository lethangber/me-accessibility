base_dir = r"d:\OneDrive\Wordpress Plugins\New Plugins\ME Accessibility\ME Accessibility\languages"

for lang in langs:
    file_path = os.path.join(base_dir, f"admin-{lang}.json")
    if os.path.exists(file_path):
        print(f"Updating {file_path}...")
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # Merge new translations
        for k, v in translations[lang].items():
            data[k] = v
            
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

print("Translations update completed!")
